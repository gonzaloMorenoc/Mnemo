class TestPutFileShaOmit:
    """Unit tests for the _put_file sha-key logic."""

    def _make_host(self, captured):
        class _CaptureSess:
            def put(self, url, json=None, headers=None, timeout=None):
                captured["payload"] = json
                return _Resp(200, {"commit": {"sha": "x"}})

        return GitHubCodeHost(
            auth=_auth(), installation_id="9",
            repo_full_name=REPO, session=_CaptureSess(),
        )

    def test_omits_sha_when_file_sha_is_none(self):
        captured = {}
        host = self._make_host(captured)
        host._put_file("f.ts", "content", None, "branch", message="msg")
        assert "sha" not in captured["payload"]

    def test_omits_sha_when_file_sha_is_empty_string(self):
        captured = {}
        host = self._make_host(captured)
        host._put_file("f.ts", "content", "", "branch", message="msg")
        assert "sha" not in captured["payload"]

    def test_includes_sha_when_file_sha_is_set(self):
        captured = {}
        host = self._make_host(captured)
        host._put_file("f.ts", "content", "abc123", "branch", message="msg")
        assert captured["payload"]["sha"] == "abc123"
